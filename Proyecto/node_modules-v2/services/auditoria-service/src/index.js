
import 'dotenv/config';

import { ApolloServer } from '@apollo/server';
import { startStandaloneServer } from '@apollo/server/standalone';
import { buildSubgraphSchema } from '@apollo/subgraph';
import { parse } from 'graphql';

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

import cassandra from 'cassandra-driver';
import amqp from 'amqplib';

import { runtimeConfig } from './infrastructure/runtime-config.js';
import { actorFromGatewayRequest } from './infrastructure/gateway-identity.js';
import { assertCanViewAudit } from './domain/authorization.js';

// --------------------------------------------------
// CONFIGURACIÓN
// --------------------------------------------------

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const typeDefs = parse(
  fs.readFileSync(
    path.join(__dirname, 'schema.graphql'),
    'utf8'
  )
);

const QUEUE_NAME = 'transmisiones-auditoria';
const DLQ_NAME = 'transmisiones-auditoria.dlq';

const PREFETCH_LIMIT = 50;
const MAX_RETRIES = 3;
const RECONNECT_DELAY = 5000;

// --------------------------------------------------
// SCYLLADB
// --------------------------------------------------

const scyllaClient = new cassandra.Client({
  contactPoints: [runtimeConfig.scyllaHost],
  localDataCenter: 'datacenter1',
  keyspace: 'system',
  protocolOptions: {
    port: runtimeConfig.scyllaPort
  }
});

function bucketDeHoy() {
  return new Date().toISOString().slice(0, 10);
}

async function initScyllaSchema() {
  try {
    await scyllaClient.connect();

    await scyllaClient.execute(`
      CREATE KEYSPACE IF NOT EXISTS auditoria
      WITH replication = {
        'class': 'SimpleStrategy',
        'replication_factor': 1
      }
    `);

    const clientAudit = new cassandra.Client({
      contactPoints: [runtimeConfig.scyllaHost],
      localDataCenter: 'datacenter1',
      keyspace: 'auditoria',
      protocolOptions: {
        port: runtimeConfig.scyllaPort
      }
    });

    await clientAudit.connect();

    await clientAudit.execute(`
      CREATE TABLE IF NOT EXISTS logs_auditoria (
        bucket text,
        fecha timestamp,
        id uuid,
        evento text,
        detalle text,
        PRIMARY KEY (bucket, fecha, id)
      ) WITH CLUSTERING ORDER BY (fecha DESC)
    `);

    console.log(
      'ScyllaDB (Dominio de Auditoría) conectado y esquema de base de datos verificado.'
    );

    return clientAudit;

  } catch (err) {
    console.warn(
      '⚠️ No se pudo iniciar ScyllaDB:',
      err.message
    );

    return null;
  }
}

const auditDb = await initScyllaSchema();

// --------------------------------------------------
// UTILIDAD DE ESPERA
// --------------------------------------------------

function esperar(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

// --------------------------------------------------
// PROCESAMIENTO DE EVENTOS
// --------------------------------------------------

async function guardarEvento(evento) {
  if (!auditDb) {
    throw new Error(
      'ScyllaDB no está disponible. No se puede guardar el evento.'
    );
  }

  const query = `
    INSERT INTO logs_auditoria
      (bucket, fecha, id, evento, detalle)
    VALUES (?, toTimestamp(now()), uuid(), ?, ?)
  `;

  await auditDb.execute(
    query,
    [
      bucketDeHoy(),
      evento.event,
      JSON.stringify(evento.payload)
    ],
    { prepare: true }
  );

  console.log(
    `💾 Evento ${evento.event} guardado en ScyllaDB.`
  );
}

// --------------------------------------------------
// REINTENTOS Y DEAD LETTER QUEUE
// --------------------------------------------------

async function manejarErrorMensaje(channel, msg, error) {
  const headers = msg.properties.headers || {};

  const intentos = Number(
    headers['x-retry-count'] || 0
  );

  try {
    if (intentos < MAX_RETRIES) {

      channel.sendToQueue(
        QUEUE_NAME,
        msg.content,
        {
          persistent: true,
          contentType: msg.properties.contentType,
          headers: {
            ...headers,
            'x-retry-count': intentos + 1
          }
        }
      );

      await channel.waitForConfirms();

      channel.ack(msg);

      console.warn(
        `🔄 Mensaje reencolado. Reintento ${intentos + 1}/${MAX_RETRIES}.`
      );

    } else {

      channel.sendToQueue(
        DLQ_NAME,
        msg.content,
        {
          persistent: true,
          contentType: msg.properties.contentType,
          headers: {
            ...headers,
            'x-retry-count': intentos,
            'x-error-message': error.message
          }
        }
      );

      await channel.waitForConfirms();

      channel.ack(msg);

      console.error(
        `☠️ Mensaje enviado a Dead Letter Queue después de ${MAX_RETRIES} reintentos.`
      );
    }

  } catch (publishError) {

    console.error(
      '❌ No se pudo reenviar el mensaje:',
      publishError.message
    );

    try {
      channel.nack(msg, false, true);
    } catch {
      console.error(
        'El canal se cerró antes de poder reencolar el mensaje.'
      );
    }
  }
}

// --------------------------------------------------
// CONSUMIDOR RABBITMQ
// --------------------------------------------------

async function startRabbitConsumer() {

  if (!auditDb) {
    console.error(
      '⚠️ Worker detenido: ScyllaDB no está disponible. Los mensajes permanecerán en RabbitMQ.'
    );
    return;
  }

  while (true) {

    let conn = null;
    let channel = null;

    try {

      console.log(
        '🐇 Conectando consumidor con RabbitMQ...'
      );

      conn = await amqp.connect(
        runtimeConfig.rabbitMqUrl
      );

      channel = await conn.createConfirmChannel();

      conn.on('error', error => {
        console.error(
          'RabbitMQ connection error:',
          error.message
        );
      });

      await channel.assertQueue(
        QUEUE_NAME,
        { durable: true }
      );

      await channel.assertQueue(
        DLQ_NAME,
        { durable: true }
      );

      await channel.prefetch(PREFETCH_LIMIT);

      console.log(
        `📥 Worker conectado. Prefetch configurado en ${PREFETCH_LIMIT}.`
      );

      console.log(
        `📥 Escuchando eventos en [${QUEUE_NAME}].`
      );

      await channel.consume(
        QUEUE_NAME,
        async msg => {

          if (msg === null) return;

          try {

            const content = JSON.parse(
              msg.content.toString()
            );

            console.log(
              '📨 Evento recibido de la cola:',
              content
            );

            await guardarEvento(content);

            channel.ack(msg);

          } catch (error) {

            console.error(
              '❌ Error procesando evento:',
              error.message
            );

            await manejarErrorMensaje(
              channel,
              msg,
              error
            );
          }
        },
        { noAck: false }
      );

      await new Promise(resolve => {
        conn.once('close', resolve);
      });

      console.warn(
        '⚠️ Conexión RabbitMQ cerrada.'
      );

    } catch (error) {

      console.error(
        '❌ Error en el Worker RabbitMQ:',
        error.message
      );

    } finally {

      try {
        if (channel) {
          await channel.close();
        }
      } catch {}

      try {
        if (conn) {
          await conn.close();
        }
      } catch {}
    }

    console.log(
      `🔄 Intentando reconectar RabbitMQ en ${RECONNECT_DELAY / 1000} segundos...`
    );

    await esperar(RECONNECT_DELAY);
  }
}

startRabbitConsumer().catch(error => {
  console.error(
    'Error fatal del Worker:',
    error.message
  );
});

// --------------------------------------------------
// GRAPHQL RESOLVERS
// --------------------------------------------------

const resolvers = {

  Query: {

    buscarLogsAuditoria: async (_, { limite }, { actor }) => {

      assertCanViewAudit(actor);

      if (!auditDb) return [];

      try {

        const result = await auditDb.execute(
          `
            SELECT *
            FROM logs_auditoria
            WHERE bucket = ?
            LIMIT ?
          `,
          [bucketDeHoy(), limite],
          { prepare: true }
        );

        return result.rows.map(row => ({
          id: row.id.toString(),
          evento: row.evento,
          detalle: row.detalle,
          fecha: row.fecha.toISOString()
        }));

      } catch (error) {

        console.error(
          'Error al consultar ScyllaDB:',
          error.message
        );

        return [];
      }
    }
  }
};

// --------------------------------------------------
// APOLLO SERVER
// --------------------------------------------------

const server = new ApolloServer({
  schema: buildSubgraphSchema([
    { typeDefs, resolvers }
  ])
});

const port = runtimeConfig.port;

const { url } = await startStandaloneServer(
  server,
  {
    listen: { port },

    context: async ({ req }) => ({
      actor: actorFromGatewayRequest(req, runtimeConfig.jwtSecret)
    })
  }
);

console.log(
  `🚀 📊 Subgrafo de Auditoría (ScyllaDB + RabbitMQ Consumer) levantado exitosamente en: ${url}`
);