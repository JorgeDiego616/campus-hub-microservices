import 'dotenv/config';
import { ApolloServer } from '@apollo/server';
import { startStandaloneServer } from '@apollo/server/standalone';
import { buildSubgraphSchema } from '@apollo/subgraph';
import { parse } from 'graphql';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

import { runtimeConfig } from './infrastructure/runtime-config.js';
import { connectMongo } from './infrastructure/mongo-connection.js';
import { createEspacioRepository } from './infrastructure/mongoose-repositories.js';
import { createRabbitPublisher } from './infrastructure/rabbitmq-event-publisher.js';
import { createMapaUseCases } from './application/mapa-use-cases.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const typeDefs = parse(
  fs.readFileSync(
    path.join(__dirname, 'schema.graphql'),
    'utf8'
  )
);

async function main() {
  await connectMongo();

  const repository = createEspacioRepository();

  const eventPublisher = await createRabbitPublisher(
    runtimeConfig.rabbitMqUrl
  );

  const useCases = createMapaUseCases({
    repository,
    eventPublisher
  });

  const resolvers = {
    Query: {
      espacio: async (_, { id }) => {
        return useCases.obtenerEspacio(id);
      },

      espacios: async (_, { tipo, activo }) => {
        return useCases.listarEspacios({
          tipo,
          activo
        });
      }
    },

    Mutation: {
      crearEspacio: async (_, { input }) => {
        return useCases.crearEspacio(input);
      },

      desactivarEspacio: async (_, { id }) => {
        return useCases.desactivarEspacio(id);
      },

      activarEspacio: async (_, { id }) => {
        return useCases.activarEspacio(id);
      }
    },

    Espacio: {
      __resolveReference: async (reference) => {
        return useCases.obtenerEspacio(reference.id);
      }
    }
  };

  const server = new ApolloServer({
    schema: buildSubgraphSchema([
      {
        typeDefs,
        resolvers
      }
    ])
  });

  const { url } = await startStandaloneServer(server, {
    listen: {
      port: runtimeConfig.port
    }
  });

  console.log(
    `🗺️ Subgrafo de Mapa levantado exitosamente en: ${url}`
  );
}

main().catch((error) => {
  console.error(
    '❌ Error fatal al iniciar el subgrafo de Mapa:',
    error
  );

  process.exit(1);
});