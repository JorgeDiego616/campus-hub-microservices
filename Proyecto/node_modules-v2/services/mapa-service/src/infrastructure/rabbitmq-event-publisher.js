import amqp from 'amqplib';

const QUEUE_NAME = 'transmisiones-auditoria';

export async function createRabbitPublisher(rabbitMqUrl) {
  let channel = null;

  try {
    const connection = await amqp.connect(rabbitMqUrl);

    channel = await connection.createChannel();

    await channel.assertQueue(QUEUE_NAME, {
      durable: true
    });

    console.log('RabbitMQ conectado. Canal listo para Mapa.');
  } catch (error) {
    console.warn(
      '⚠️ RabbitMQ no disponible en Mapa:',
      error.message
    );
  }

  return {
    async publish(event, payload) {
      if (!channel) {
        console.warn(
          `⚠️ Evento ${event} no enviado porque RabbitMQ no está disponible.`
        );
        return;
      }

      const message = {
        event,
        payload: {
          ...payload,
          fecha: new Date()
        }
      };

      channel.sendToQueue(
        QUEUE_NAME,
        Buffer.from(JSON.stringify(message)),
        {
          persistent: true
        }
      );

      console.log(
        `📨 Evento '${event}' enviado a RabbitMQ desde Mapa.`
      );
    }
  };
}