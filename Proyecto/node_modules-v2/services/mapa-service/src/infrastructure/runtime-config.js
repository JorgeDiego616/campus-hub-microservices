const profiles = {
  local: {
    mongoUri:
      'mongodb://admin:password123@localhost:27018/mapa?authSource=admin',
    rabbitMqUrl:
      'amqp://guest:guest@localhost:5673',
    redisUrl:
      'redis://default:password123@localhost:6380'
  },

  docker: {
    mongoUri:
      'mongodb://admin:password123@mongodb:27017/mapa?authSource=admin',
    rabbitMqUrl:
      'amqp://guest:guest@rabbitmq:5672',
    redisUrl:
      'redis://default:password123@redis-stack:6379'
  }
};

const mode = process.env.INFRASTRUCTURE_MODE || 'local';

if (!profiles[mode]) {
  throw new Error(
    'INFRASTRUCTURE_MODE debe ser "local" o "docker".'
  );
}

const profile = profiles[mode];
const configuredRedisCacheTtl = Number.parseInt(
  process.env.REDIS_CACHE_TTL_SECONDS || '60',
  10
);
const configuredPort = Number.parseInt(
  process.env.PORT_MAPA || '4002',
  10
);

export const runtimeConfig = {
  mongoUri: process.env.MONGODB_URI || profile.mongoUri,
  rabbitMqUrl: process.env.RABBITMQ_URL || profile.rabbitMqUrl,
  redisUrl: process.env.REDIS_URL || profile.redisUrl,
  redisCacheTtlSeconds:
    Number.isInteger(configuredRedisCacheTtl) && configuredRedisCacheTtl > 0
      ? configuredRedisCacheTtl
      : 60,
  port:
    Number.isInteger(configuredPort) && configuredPort > 0
      ? configuredPort
      : 4002
};
