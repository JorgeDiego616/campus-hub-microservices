import 'dotenv/config';
import { ApolloServer } from '@apollo/server';
import { startStandaloneServer } from '@apollo/server/standalone';
import { buildSubgraphSchema } from '@apollo/subgraph';
import { parse } from 'graphql';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import mongoose from 'mongoose';
import amqp from 'amqplib';
import { EquipoModel } from './infrastructure/mongoose-models.js';
import { Equipo } from './domain/entities.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const typeDefs = parse(fs.readFileSync(path.join(__dirname, 'schema.graphql'), 'utf8'));

// Conectar a MongoDB
const mongoUri = process.env.MONGODB_URI || 'mongodb://localhost:27017/resistencia';

async function conectarBaseDatos() {
  try {
    await mongoose.connect(mongoUri);
    console.log("🔥 Conexión exitosa a MongoDB (deportes-service).");
  } catch (error) {
    console.error("❌ Error de conexión a MongoDB:", error.message);
    process.exit(1);
  }
}

// Inicializar conexión con el Broker de Mensajería (RabbitMQ)
let rabbitChannel;
async function initRabbit() {
  try {
    const conn = await amqp.connect(process.env.RABBITMQ_URL || 'amqp://guest:guest@localhost:5672');
    rabbitChannel = await conn.createChannel();
    await rabbitChannel.assertQueue('transmisiones-auditoria', { durable: true });
    console.log("RabbitMQ conectado. Canal listo para el dominio de Deportes.");
  } catch (err) {
    console.error("No se pudo establecer conexión con RabbitMQ:", err.message);
  }
}

const resolvers = {
  Query: {
    verEquipo: async (_, { id }) => {
      const doc = await EquipoModel.findById(id);
      if (!doc) return null;
      return {
        id: doc._id,
        nombre: doc.nombre,
        deporte: doc.deporte,
        categoria: doc.categoria,
        practicas: doc.practicas ?? []
      };
    },

    allEquipos: async () => {
      const docs = await EquipoModel.find({});
      return docs.map((doc) => ({
        id: doc._id,
        nombre: doc.nombre,
        deporte: doc.deporte,
        categoria: doc.categoria,
        practicas: doc.practicas ?? []
      }));
    },

    // Resolver analítico utilizando agregación de MongoDB
    reportePracticasPorDeporte: async () => {
      try {
        const resultado = await EquipoModel.aggregate([
          // Etapa 1: Aplanar el arreglo de prácticas incrustadas
          { $unwind: "$practicas" },
          // Etapa 2: Agrupar por deporte y calcular métricas
          {
            $group: {
              _id: "$deporte",
              totalPracticas: { $sum: 1 },
              equiposAsociados: { $addToSet: "$nombre" }
            }
          },
          // Etapa 3: Ordenar por volumen descendente
          { $sort: { totalPracticas: -1 } }
        ]);

        return resultado.map((item) => ({
          deporte: item._id,
          totalPracticas: item.totalPracticas,
          equiposAsociados: item.equiposAsociados
        }));
      } catch (err) {
        console.error("❌ Error en el pipeline analítico:", err.message);
        throw new Error("No se pudo generar el reporte de prácticas.");
      }
    }
  },

  Mutation: {
    registrarEquipo: async (_, { nombre, deporte, categoria }) => {
      // Guardar en la persistencia
      const nuevoEquipo = new EquipoModel({ nombre, deporte, categoria });
      const doc = await nuevoEquipo.save();

      // Emitir evento de dominio a RabbitMQ para auditoría
      if (rabbitChannel) {
        const event = {
          event: "EQUIPO_REGISTRADO",
          payload: { id: doc._id, nombre: doc.nombre, fecha: new Date() }
        };
        rabbitChannel.sendToQueue('transmisiones-auditoria', Buffer.from(JSON.stringify(event)), { persistent: true });
        console.log("Evento 'EQUIPO_REGISTRADO' enviado asíncronamente al broker.");
      }

      return { id: doc._id, nombre: doc.nombre, deporte: doc.deporte, categoria: doc.categoria };
    },

    registrarPractica: async (_, { equipoId, fecha, horaInicio, horaFin, ubicacion }) => {
      // 1. Buscar el equipo padre
      const equipoDoc = await EquipoModel.findById(equipoId);
      if (!equipoDoc) {
        throw new Error("El equipo de destino no existe.");
      }

      // 2. Validar la regla de negocio usando la clase pura del dominio
      const equipoDominio = new Equipo(
        equipoDoc._id,
        equipoDoc.nombre,
        equipoDoc.deporte,
        equipoDoc.categoria,
        equipoDoc.practicas
      );
      equipoDominio.validarHorarioPractica({ fecha, horaInicio, horaFin, ubicacion });

      // 3. Insertar la práctica en el arreglo incrustado
      equipoDoc.practicas.push({ fecha, horaInicio, horaFin, ubicacion });

      // 4. Guardar el documento padre
      const equipoActualizado = await equipoDoc.save();
      const practicaGuardada = equipoActualizado.practicas[equipoActualizado.practicas.length - 1];

      return {
        id: practicaGuardada._id,
        fecha: practicaGuardada.fecha,
        horaInicio: practicaGuardada.horaInicio,
        horaFin: practicaGuardada.horaFin,
        ubicacion: practicaGuardada.ubicacion
      };
    }
  },

  Equipo: {
    __resolveReference: async (reference) => {
      const doc = await EquipoModel.findById(reference.id);
      if (!doc) return null;
      return {
        id: doc._id,
        nombre: doc.nombre,
        deporte: doc.deporte,
        categoria: doc.categoria,
        practicas: doc.practicas ?? []
      };
    }
  }
};

// --- Arranque del servidor ---
async function main() {
  await conectarBaseDatos();
  await initRabbit();

  const server = new ApolloServer({
    schema: buildSubgraphSchema({ typeDefs, resolvers })
  });

  const port = parseInt(process.env.PORT_ULSA) || 4001;
  const { url } = await startStandaloneServer(server, {
    listen: { port }
  });

  console.log(`🏅 Subgrafo de Deportes levantado exitosamente en: ${url}`);
}

main().catch((err) => {
  console.error("❌ Error fatal al iniciar el subgrafo de Deportes:", err);
  process.exit(1);
});