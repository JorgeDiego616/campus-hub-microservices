const profiles = {
  local: { mongoUri: 'mongodb://admin:password123@localhost:27018/academico?authSource=admin', rabbitMqUrl: 'amqp://guest:guest@localhost:5673' },
  docker: { mongoUri: 'mongodb://admin:password123@mongodb:27017/academico?authSource=admin', rabbitMqUrl: 'amqp://guest:guest@rabbitmq:5672' }
};
const mode = process.env.INFRASTRUCTURE_MODE || 'local';
if (!profiles[mode]) throw new Error('INFRASTRUCTURE_MODE debe ser "local" o "docker".');
const profile = profiles[mode];
const jwtSecret = process.env.JWT_SECRET;

if (typeof jwtSecret !== 'string' || jwtSecret.trim().length === 0) {
  throw new Error(
    'JWT_SECRET es obligatorio en academico-service para validar identidad del Gateway.'
  );
}

const configuredPort = Number.parseInt(
  process.env.PORT_ACADEMICO || '4004',
  10
);

export const runtimeConfig = {
  mongoUri: process.env.MONGODB_URI || profile.mongoUri,
  rabbitMqUrl: process.env.RABBITMQ_URL || profile.rabbitMqUrl,
  jwtSecret,
  port:
    Number.isInteger(configuredPort) && configuredPort > 0
      ? configuredPort
      : 4004
};
