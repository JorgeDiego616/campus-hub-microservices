import amqp from 'amqplib';
export class RabbitMqEventPublisher {
  constructor(url, queue = 'transmisiones-auditoria') { this.url = url; this.queue = queue; this.channel = null; }
  async connect() { const connection = await amqp.connect(this.url); this.channel = await connection.createChannel(); await this.channel.assertQueue(this.queue, { durable: true }); }
  async publish(event, payload) { if (!this.channel) return; this.channel.sendToQueue(this.queue, Buffer.from(JSON.stringify({ event, payload: { ...payload, fecha: new Date() } })), { persistent: true }); }
}
