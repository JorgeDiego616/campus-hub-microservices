export const Roles = Object.freeze({
  ESTUDIANTE: 'ESTUDIANTE',
  BECARIO: 'BECARIO',
  PROFESOR: 'PROFESOR',
  ADMIN: 'ADMIN'
});

export function requireActor(actor) {
  if (!actor?.id || !actor?.rol) throw new Error('Se requiere una identidad autenticada.');
}

export function assertCanAccessStudent(actor, alumnoId) {
  requireActor(actor);
  if (actor.rol === Roles.ADMIN) return;
  if (![Roles.ESTUDIANTE, Roles.BECARIO].includes(actor.rol) || String(actor.id) !== String(alumnoId)) {
    throw new Error('No tienes permiso para consultar esta información académica.');
  }
}

export function assertCanManageCatalog(actor) {
  requireActor(actor);
  if (actor.rol !== Roles.ADMIN) throw new Error('Solo ADMIN puede administrar catálogos académicos.');
}

export function assertProfessorOwnsAssignment(actor, asignacion) {
  requireActor(actor);
  if (actor.rol === Roles.ADMIN) return;
  if (actor.rol !== Roles.PROFESOR || String(actor.id) !== String(asignacion.profesorId)) {
    throw new Error('El profesor no tiene asignada esta materia o grupo.');
  }
}

export function assertCanRegisterHours(actor, alumnoId) {
  assertCanAccessStudent(actor, alumnoId);
}
