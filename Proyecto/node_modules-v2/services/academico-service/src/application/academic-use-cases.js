import {
  AsignacionMateria,
  Calificacion,
  Carrera,
  Examen,
  Falta,
  HorasBecarias,
  HorasComplementarias,
  Inscripcion,
  Materia,
  PerfilAcademico,
  Periodo
} from '../domain/entities.js';
import {
  assertCanAccessStudent,
  assertCanManageCatalog,
  assertCanRegisterHours,
  assertProfessorOwnsAssignment,
  requireActor,
  Roles
} from '../domain/authorization.js';

export class AcademicUseCases {
  constructor({ repositories, eventPublisher }) {
    this.repositories = repositories;
    this.eventPublisher = eventPublisher;
  }

  async publish(event, payload) {
    await this.eventPublisher.publish(event, payload);
  }

  async crearCarrera(actor, input) {
    assertCanManageCatalog(actor);
    const carrera = new Carrera(input);
    const result = await this.repositories.carreras.create(carrera);
    await this.publish('CARRERA_CREADA', { id: result.id, nombre: result.nombre });
    return result;
  }

  listarCarreras() { return this.repositories.carreras.findAll(); }

  async crearMateria(actor, input) {
    assertCanManageCatalog(actor);
    const materia = new Materia(input);
    return this.repositories.materias.create(materia);
  }

  listarMaterias() { return this.repositories.materias.findAll(); }

  async crearPeriodo(actor, input) {
    assertCanManageCatalog(actor);
    const periodo = new Periodo(input);
    return this.repositories.periodos.create(periodo);
  }

  listarPeriodos() { return this.repositories.periodos.findAll(); }

  async crearPerfil(actor, input) {
    assertCanManageCatalog(actor);
    const perfil = new PerfilAcademico(input);
    await this.repositories.carreras.requireById(perfil.carreraId);
    return this.repositories.perfiles.upsertByUser(perfil);
  }

  async perfilAcademico(actor, usuarioId) {
    assertCanAccessStudent(actor, usuarioId);
    return this.repositories.perfiles.findByUser(usuarioId);
  }

  async crearAsignacion(actor, input) {
    assertCanManageCatalog(actor);
    const asignacion = new AsignacionMateria(input);
    await Promise.all([
      this.repositories.materias.requireById(asignacion.materiaId),
      this.repositories.periodos.requireById(asignacion.periodoId)
    ]);
    return this.repositories.asignaciones.create(asignacion);
  }

  async asignaciones(actor, periodoId) {
    requireActor(actor);
    if (actor.rol === Roles.ADMIN) return this.repositories.asignaciones.findAll(periodoId);
    if (actor.rol === Roles.PROFESOR) return this.repositories.asignaciones.findByProfessor(actor.id, periodoId);
    if ([Roles.ESTUDIANTE, Roles.BECARIO].includes(actor.rol)) {
      return this.repositories.asignaciones.findByStudent(actor.id, periodoId);
    }
    throw new Error('No tienes permiso para consultar asignaciones.');
  }

  async inscribir(actor, input) {
    assertCanAccessStudent(actor, input.alumnoId);
    const inscripcion = new Inscripcion(input);
    await this.repositories.asignaciones.requireById(inscripcion.asignacionMateriaId);
    Inscripcion.asegurarNoDuplicada(await this.repositories.inscripciones.exists(inscripcion.alumnoId, inscripcion.asignacionMateriaId));
    const result = await this.repositories.inscripciones.create(inscripcion);
    await this.publish('INSCRIPCION_CREADA', { id: result.id, alumnoId: result.alumnoId, asignacionMateriaId: result.asignacionMateriaId });
    return result;
  }

  async inscripciones(actor, alumnoId) {
    requireActor(actor);
    if (actor.rol === Roles.ADMIN) return this.repositories.inscripciones.findByStudent(alumnoId);
    if (actor.rol === Roles.PROFESOR) return this.repositories.inscripciones.findByStudentForProfessor(alumnoId, actor.id);
    assertCanAccessStudent(actor, alumnoId);
    return this.repositories.inscripciones.findByStudent(alumnoId);
  }

  async requireManagedInscripcion(actor, inscripcionId) {
    const inscripcion = await this.repositories.inscripciones.requireById(inscripcionId);
    const asignacion = await this.repositories.asignaciones.requireById(inscripcion.asignacionMateriaId);
    assertProfessorOwnsAssignment(actor, asignacion);
    return { inscripcion, asignacion };
  }

  async registrarCalificacion(actor, input) {
    await this.requireManagedInscripcion(actor, input.inscripcionId);
    const calificacion = new Calificacion(input);
    const result = await this.repositories.calificaciones.create(calificacion);
    await this.publish('CALIFICACION_REGISTRADA', { id: result.id, inscripcionId: result.inscripcionId });
    return result;
  }

  async calificaciones(actor, inscripcionId) {
    const inscripcion = await this.repositories.inscripciones.requireById(inscripcionId);
    if (actor.rol === Roles.PROFESOR || actor.rol === Roles.ADMIN) await this.requireManagedInscripcion(actor, inscripcionId);
    else assertCanAccessStudent(actor, inscripcion.alumnoId);
    return this.repositories.calificaciones.findByInscripcion(inscripcionId);
  }

  async registrarFalta(actor, input) {
    await this.requireManagedInscripcion(actor, input.inscripcionId);
    const falta = new Falta(input);
    const result = await this.repositories.faltas.create(falta);
    await this.publish('FALTA_REGISTRADA', { id: result.id, inscripcionId: result.inscripcionId });
    return result;
  }

  async faltas(actor, inscripcionId) {
    const inscripcion = await this.repositories.inscripciones.requireById(inscripcionId);
    if (actor.rol === Roles.PROFESOR || actor.rol === Roles.ADMIN) await this.requireManagedInscripcion(actor, inscripcionId);
    else assertCanAccessStudent(actor, inscripcion.alumnoId);
    return this.repositories.faltas.findByInscripcion(inscripcionId);
  }

  async registrarExamen(actor, input) {
    const examen = new Examen(input);
    const asignacion = await this.repositories.asignaciones.requireById(examen.asignacionMateriaId);
    assertProfessorOwnsAssignment(actor, asignacion);
    const periodoDocument = await this.repositories.periodos.requireById(examen.periodoId);
    const periodo = new Periodo(periodoDocument);
    examen.validarPeriodo(periodo, asignacion.periodoId);
    const result = await this.repositories.examenes.create(examen);
    await this.publish('EXAMEN_REGISTRADO', { id: result.id, asignacionMateriaId: result.asignacionMateriaId });
    return result;
  }

  async examenes(actor, asignacionMateriaId) {
    const asignacion = await this.repositories.asignaciones.requireById(asignacionMateriaId);
    requireActor(actor);
    if (actor.rol === Roles.PROFESOR || actor.rol === Roles.ADMIN) {
      assertProfessorOwnsAssignment(actor, asignacion);
    } else {
      assertCanAccessStudent(actor, actor.id);
      const estaInscrito = await this.repositories.inscripciones.exists(actor.id, asignacionMateriaId);
      if (!estaInscrito) throw new Error('No tienes una inscripción en esta asignación.');
    }
    return this.repositories.examenes.findByAsignacion(asignacionMateriaId);
  }

  async registrarHorasBecarias(actor, input) {
    assertCanRegisterHours(actor, input.alumnoId);
    await this.repositories.periodos.requireById(input.periodoId);
    return this.repositories.horasBecarias.create(new HorasBecarias(input));
  }

  async registrarHorasComplementarias(actor, input) {
    assertCanRegisterHours(actor, input.alumnoId);
    await this.repositories.periodos.requireById(input.periodoId);
    return this.repositories.horasComplementarias.create(new HorasComplementarias(input));
  }
}
