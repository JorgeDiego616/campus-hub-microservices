import 'dotenv/config';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ApolloServer } from '@apollo/server';
import { startStandaloneServer } from '@apollo/server/standalone';
import { buildSubgraphSchema } from '@apollo/subgraph';
import { parse } from 'graphql';
import { AcademicUseCases } from './application/academic-use-cases.js';
import { connectMongo } from './infrastructure/mongo-connection.js';
import { createMongooseRepositories } from './infrastructure/mongoose-repositories.js';
import { RabbitMqEventPublisher } from './infrastructure/rabbitmq-event-publisher.js';
import { runtimeConfig } from './infrastructure/runtime-config.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const typeDefs = parse(fs.readFileSync(path.join(__dirname, 'schema.graphql'), 'utf8'));

function actorFromRequest(request) {
  const userId = request.headers?.['x-user-id'];
  const userRole = request.headers?.['x-user-role'];

  if (!userId || !userRole) {
    return null;
  }

  return {
    id: userId,
    rol: userRole
  };
}

const resolvers = {
  Query: {
    carreras: (_, __, { useCases }) => useCases.listarCarreras(),
    materias: (_, __, { useCases }) => useCases.listarMaterias(),
    periodos: (_, __, { useCases }) => useCases.listarPeriodos(),
    perfilAcademico: (_, { usuarioId }, { actor, useCases }) => useCases.perfilAcademico(actor, usuarioId),
    asignaciones: (_, { periodoId }, { actor, useCases }) => useCases.asignaciones(actor, periodoId),
    inscripciones: (_, { alumnoId }, { actor, useCases }) => useCases.inscripciones(actor, alumnoId),
    calificaciones: (_, { inscripcionId }, { actor, useCases }) => useCases.calificaciones(actor, inscripcionId),
    faltas: (_, { inscripcionId }, { actor, useCases }) => useCases.faltas(actor, inscripcionId),
    examenes: (_, { asignacionMateriaId }, { actor, useCases }) => useCases.examenes(actor, asignacionMateriaId)
  },
  Mutation: {
    crearCarrera: (_, { input }, { actor, useCases }) => useCases.crearCarrera(actor, input),
    crearMateria: (_, { input }, { actor, useCases }) => useCases.crearMateria(actor, input),
    crearPeriodo: (_, { input }, { actor, useCases }) => useCases.crearPeriodo(actor, input),
    guardarPerfilAcademico: (_, { input }, { actor, useCases }) => useCases.crearPerfil(actor, input),
    crearAsignacionMateria: (_, { input }, { actor, useCases }) => useCases.crearAsignacion(actor, input),
    inscribirAlumno: (_, { input }, { actor, useCases }) => useCases.inscribir(actor, input),
    registrarCalificacion: (_, { input }, { actor, useCases }) => useCases.registrarCalificacion(actor, input),
    registrarFalta: (_, { input }, { actor, useCases }) => useCases.registrarFalta(actor, input),
    registrarExamen: (_, { input }, { actor, useCases }) => useCases.registrarExamen(actor, input),
    registrarHorasBecarias: (_, { input }, { actor, useCases }) => useCases.registrarHorasBecarias(actor, input),
    registrarHorasComplementarias: (_, { input }, { actor, useCases }) => useCases.registrarHorasComplementarias(actor, input)
  },
  Periodo: { fechaInicio: (periodo) => new Date(periodo.fechaInicio).toISOString(), fechaFin: (periodo) => new Date(periodo.fechaFin).toISOString() },
  Calificacion: { fechaRegistro: (calificacion) => new Date(calificacion.fechaRegistro).toISOString() },
  Falta: { fecha: (falta) => new Date(falta.fecha).toISOString() },
  Examen: { fecha: (examen) => new Date(examen.fecha).toISOString() }
};

async function main() {
  await connectMongo(runtimeConfig.mongoUri);
  const eventPublisher = new RabbitMqEventPublisher(runtimeConfig.rabbitMqUrl);
  try { await eventPublisher.connect(); } catch (error) { console.warn(`RabbitMQ no disponible; los eventos de auditoría no se publicarán: ${error.message}`); }
  const useCases = new AcademicUseCases({ repositories: createMongooseRepositories(), eventPublisher });
  const server = new ApolloServer({ schema: buildSubgraphSchema([{ typeDefs, resolvers }]) });
  const { url } = await startStandaloneServer(server, { listen: { port: runtimeConfig.port }, context: async ({ req }) => ({ actor: actorFromRequest(req), useCases }) });
  console.log(`Subgrafo Académico levantado en ${url}`);
}

main().catch((error) => { console.error('Error fatal al iniciar academico-service:', error); process.exit(1); });
