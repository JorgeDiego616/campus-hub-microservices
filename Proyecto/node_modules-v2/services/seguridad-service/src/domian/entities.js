// Entidad de Dominio (Modelo de Negocio Puro - DDD)
export class Usuario {
  constructor(id, matricula, nombre, email, rol) {
    this.id = id;
    this.matricula = matricula;
    this.nombre = nombre;
    this.email = email;
    this.rol = rol;
  }

  // Regla de negocio: la matrícula debe tener entre 6 y 10 dígitos numéricos.
  validarMatricula() {
    const formatoValido = /^\d{6,10}$/.test(this.matricula);
    if (!formatoValido) {
      throw new Error("La matrícula debe contener solo dígitos, entre 6 y 10 caracteres.");
    }
  }

  // Regla de negocio: solo estos roles existen en el sistema.
  validarRol() {
    const rolesPermitidos = ['ESTUDIANTE', 'ENTRENADOR', 'PROFESOR', 'ADMIN', 'BECARIO'];
    if (!rolesPermitidos.includes(this.rol)) {
      throw new Error(`Rol inválido: ${this.rol}.`);
    }
  }
}