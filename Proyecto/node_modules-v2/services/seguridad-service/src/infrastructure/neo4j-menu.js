const MENU_NODES = [
  { id: 'home', title: 'Inicio', order: 1 },
  { id: 'teams', title: 'Equipos', order: 2 },
  { id: 'news', title: 'Noticias', order: 3 },
  { id: 'matches', title: 'Partidos', order: 4 },
  { id: 'management', title: 'Gestión', order: 5 },
  { id: 'profile', title: 'Perfil', order: 6 },
  { id: 'qr', title: 'Crear evento / QR', order: 1 }
];

const HAS_CHILD = [
  ['management', 'qr']
];

const NAVIGATES_TO = [
  ['home', 'home_home'],
  ['teams', 'team_section'],
  ['news', 'news_section'],
  ['matches', 'matches_section'],
  ['profile', 'profile_section'],
  ['qr', 'qr_screen']
];

const CAN_VIEW_MENU = [
  { role: 'ESTUDIANTE', menu: 'home' },
  { role: 'ESTUDIANTE', menu: 'teams' },
  { role: 'ESTUDIANTE', menu: 'news' },
  { role: 'ESTUDIANTE', menu: 'matches' },
  { role: 'ESTUDIANTE', menu: 'profile' },
  { role: 'PROFESOR', menu: 'management' },
  { role: 'PROFESOR', menu: 'qr' },
  { role: 'ENTRENADOR', menu: 'management' },
  { role: 'ENTRENADOR', menu: 'qr' },
  { role: 'COORDINADOR', menu: 'management' },
  { role: 'COORDINADOR', menu: 'qr' }
];

export async function clearMenuTree(driver) {
  const session = driver.session();
  try {
    await session.executeWrite(async (tx) => {
      await tx.run(`MATCH (m:MenuNode) DETACH DELETE m`);
    });
  } finally {
    await session.close();
  }
}

export async function seedMenuTree(driver) {
  const session = driver.session();
  try {
    await session.executeWrite(async (tx) => {
      for (const node of MENU_NODES) {
        await tx.run(
          `MERGE (m:MenuNode {id: $id})
           SET m.title = $title, m.order = toInteger($order)`,
          node
        );
      }

      for (const [parent, child] of HAS_CHILD) {
        await tx.run(
          `MATCH (p:MenuNode {id: $parent})
           MATCH (c:MenuNode {id: $child})
           MERGE (p)-[:HAS_CHILD]->(c)`,
          { parent, child }
        );
      }

      for (const [menu, path] of NAVIGATES_TO) {
        await tx.run(
          `MATCH (m:MenuNode {id: $menu})
           MATCH (rt:Route {path: $path})
           MERGE (m)-[:NAVIGATES_TO]->(rt)`,
          { menu, path }
        );
      }

      for (const { role, menu } of CAN_VIEW_MENU) {
        await tx.run(
          `MATCH (r:Role {name: $role})
           MATCH (m:MenuNode {id: $menu})
           MERGE (r)-[:CAN_VIEW_MENU]->(m)`,
          { role, menu }
        );
      }
    });
  } finally {
    await session.close();
  }
}
