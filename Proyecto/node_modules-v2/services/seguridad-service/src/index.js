import 'dotenv/config';
import { ApolloServer } from '@apollo/server';
import { startStandaloneServer } from '@apollo/server/standalone';
import { buildSubgraphSchema } from '@apollo/subgraph';
import { parse, GraphQLError } from 'graphql';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import mongoose from 'mongoose';
import amqp from 'amqplib';
import bcrypt from 'bcrypt';
import crypto from 'crypto';
import jwt from 'jsonwebtoken';

import neo4j from 'neo4j-driver';
import { createClient } from 'redis';

import { UsuarioModel, RolModel } from './infrastructure/mongoose-models.js';
import { runtimeConfig } from './infrastructure/runtime-config.js';
import { Usuario, ROLES_POR_DEFECTO } from './domain/entities.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const typeDefs = parse(fs.readFileSync(path.join(__dirname, 'schema.graphql'), 'utf8'));

async function conectarBaseDatos() {
  try {
    await mongoose.connect(runtimeConfig.mongoUri);
    console.log("🔥 Conexión exitosa a MongoDB (seguridad-service).");
  } catch (error) {
    console.error("❌ Error de conexión a MongoDB:", error.message);
    process.exit(1);
  }
}

// Inserta los roles por defecto si no existen (se puede reiniciar sin duplicar)
async function sembrarRoles() {
  for (const nombre of ROLES_POR_DEFECTO) {
    await RolModel.updateOne({ nombre }, { nombre }, { upsert: true });
  }
  console.log("🛡️ Roles por defecto verificados.");
}

// Inicializar conexión con redis (para caché o sesiones)
const redisUrl = process.env.REDIS_URL || 'redis://localhost:6379';
const redisClient = createClient({ url: redisUrl });
redisClient.on('error', (err) => console.error('Redis Client Error', err));
await redisClient.connect();
console.log("⚡ Redis Stack (Lista Blanca de Sesiones) conectado exitosamente.");

const SESSION_TTL_SECONDS = 3600; // 1 hora

const driver = neo4j.driver(
  process.env.NEO4J_URI || 'neo4j://localhost:7687',
  neo4j.auth.basic(
    process.env.NEO4J_USER || 'neo4j',
    process.env.NEO4J_PASSWORD || 'password'
  )
);
console.log("⚡ Neo4j conectado exitosamente.");

// Inicializar conexión con el Broker de Mensajería (RabbitMQ)
let rabbitChannel;
async function initRabbit() {
  try {
    const conn = await amqp.connect(runtimeConfig.rabbitMqUrl);
    rabbitChannel = await conn.createChannel();
    await rabbitChannel.assertQueue('transmisiones-auditoria', { durable: true });
    console.log("⚡ RabbitMQ conectado. Canal listo para el dominio de Seguridad.");
  } catch (err) {
    console.error("No se pudo establecer conexión con RabbitMQ:", err.message);
  }
}

function emitirEvento(event, payload) {
  if (!rabbitChannel) return;
  rabbitChannel.sendToQueue(
    'transmisiones-auditoria',
    Buffer.from(JSON.stringify({ event, payload: { ...payload, fecha: new Date() } })),
    { persistent: true }
  );
  console.log(`Evento '${event}' enviado asíncronamente al broker.`);
}

function aDTO(doc) {
  return {
    id: doc._id,
    matricula: doc.matricula,
    nombre: doc.nombre,
    email: doc.email,
    rol: doc.rol,
    activo: doc.activo
  };
}

const resolvers = {
  Query: {
    verUsuario: async (_, { id }) => {
      const doc = await UsuarioModel.findById(id);
      if (!doc) return null;
      return aDTO(doc);
    },

    allUsuarios: async () => {
      const docs = await UsuarioModel.find({});
      return docs.map(aDTO);
    },

    // Lista de roles con caché en Redis (5 minutos)
    roles: async () => {
      const cached = await redisClient.get('cache:roles');
      if (cached) return JSON.parse(cached);

      const docs = await RolModel.find({}).sort({ nombre: 1 });
      const data = docs.map(d => ({ id: d._id.toString(), nombre: d.nombre }));

      await redisClient.setEx('cache:roles', 300, JSON.stringify(data));
      return data;
    }
  },

  Mutation: {
    registrarUsuario: async (_, { matricula, nombre, email, password, rol }) => {
      const rolNormalizado = rol.trim().toUpperCase();

      // 1. Validar reglas de negocio usando la clase pura del dominio
      const usuarioDominio = new Usuario(null, matricula, nombre, email, rolNormalizado);
      usuarioDominio.validarMatricula();
      usuarioDominio.validarRol();

      // 1.1 El rol debe existir en la base de datos
      const rolExiste = await RolModel.findOne({ nombre: rolNormalizado });
      if (!rolExiste) {
        throw new GraphQLError("El rol no existe.", {
          extensions: {
            code: 'BAD_USER_INPUT',
            http: { status: 400 }
          }
        });
      }

      // 2. Verificar que no exista ya un usuario con esa matrícula o email
      const yaExiste = await UsuarioModel.findOne({ $or: [{ matricula }, { email }] });
      if (yaExiste) {
        throw new GraphQLError("Ya existe un usuario registrado con esa matrícula o email.", {
          extensions: {
            code: 'BAD_REQUEST',
            http: { status: 400 }
          }
        });
      }

      // 3. Hashear la contraseña antes de persistir (nunca se guarda en texto plano)
      const passwordHash = await bcrypt.hash(password, 10);

      // 4. Guardar en la persistencia
      const nuevoUsuario = new UsuarioModel({
        matricula,
        nombre,
        email,
        passwordHash,
        rol: rolNormalizado
      });
      const doc = await nuevoUsuario.save();

      // 5. Emitir evento de dominio a RabbitMQ para auditoría
      emitirEvento("USUARIO_REGISTRADO", { id: doc._id, matricula: doc.matricula });

      return aDTO(doc);
    },

    login: async (_, { email, password }) => {
      const doc = await UsuarioModel.findOne({ email });

      if (!doc) {
        throw new GraphQLError("Credenciales inválidas.", {
          extensions: {
            code: 'BAD_USER_INPUT',
            http: { status: 401 }
          }
        });
      }

      const passwordCorrecta = await bcrypt.compare(password, doc.passwordHash);
      if (!passwordCorrecta) {
        throw new GraphQLError("Credenciales inválidas.", {
          extensions: {
            code: 'BAD_USER_INPUT',
            http: { status: 401 }
          }
        });
      }

      if (!doc.activo) {
        throw new GraphQLError("Este usuario está deshabilitado.", {
          extensions: {
            code: 'FORBIDDEN',
            http: { status: 403 }
          }
        });
      }

      // Generar identificador único de sesión criptográfico (JTI)
      const jti = crypto.randomUUID();

      const token = jwt.sign(
        { id: doc._id.toString(), rol: doc.rol, jti },
        runtimeConfig.jwtSecret,
        { expiresIn: SESSION_TTL_SECONDS }
      );

      // Guardar la sesión en Redis con TTL
      await redisClient.setEx(
        `session:${jti}`,
        SESSION_TTL_SECONDS,
        JSON.stringify({ userId: doc._id.toString(), rol: doc.rol })
      );

      emitirEvento("USUARIO_LOGIN", { id: doc._id, email: doc.email });
      console.log(`🔑 Sesión iniciada y autorizada en Redis: ${'session:' + jti}`);

      return { token, usuario: aDTO(doc) };
    },

    logout: async (_, __, context) => {
      if (!context.currentUser || !context.jti) {
        throw new GraphQLError("No hay sesión activa para cerrar.", {
          extensions: { code: 'UNAUTHENTICATED', http: { status: 401 } }
        });
      }

      await redisClient.del(`session:${context.jti}`);
      emitirEvento("USUARIO_LOGOUT", { id: context.currentUser.id });
      return true;
    },

    // Solo un ADMIN puede crear roles nuevos
    crearRol: async (_, { nombre }, context) => {
      if (context.currentUser?.rol !== 'ADMIN') {
        throw new GraphQLError("Solo un ADMIN puede crear roles.", {
          extensions: { code: 'FORBIDDEN', http: { status: 403 } }
        });
      }

      const nombreNormalizado = nombre.trim().toUpperCase();

      if (!/^[A-ZÁÉÍÓÚÑ0-9_]{3,30}$/.test(nombreNormalizado)) {
        throw new GraphQLError("El rol debe tener entre 3 y 30 caracteres: letras, números o guion bajo.", {
          extensions: { code: 'BAD_USER_INPUT', http: { status: 400 } }
        });
      }

      const existe = await RolModel.findOne({ nombre: nombreNormalizado });
      if (existe) {
        throw new GraphQLError("Ese rol ya existe.", {
          extensions: { code: 'BAD_REQUEST', http: { status: 400 } }
        });
      }

      const doc = await RolModel.create({ nombre: nombreNormalizado });

      // Borrar la caché para que el rol nuevo aparezca de inmediato
      await redisClient.del('cache:roles');
      emitirEvento("ROL_CREADO", {
        id: doc._id,
        nombre: doc.nombre,
        creadoPor: context.currentUser.id
      });

      return { id: doc._id.toString(), nombre: doc.nombre };
    }
  },

  Usuario: {
    __resolveReference: async (reference) => {
      const doc = await UsuarioModel.findById(reference.id);
      if (!doc) return null;
      return aDTO(doc);
    }
  }
};

// --- Arranque del servidor ---
async function main() {
  await conectarBaseDatos();
  await sembrarRoles();
  await initRabbit();

  const server = new ApolloServer({
    schema: buildSubgraphSchema([{ typeDefs, resolvers }])
  });

  const port = runtimeConfig.port;
  const { url } = await startStandaloneServer(server, {
    listen: { port },
    context: async ({ req }) => {
      const authHeader = req.headers.authorization || '';

      if (authHeader.startsWith('Bearer ')) {
        const token = authHeader.split(' ')[1];
        try {
          // ¿La firma del JWT es válida?
          const decoded = jwt.verify(token, runtimeConfig.jwtSecret);

          // ¿La sesión existe en Redis y no ha expirado?
          const sesion = await redisClient.get(`session:${decoded.jti}`);

          if (sesion) {
            return {
              currentUser: { id: decoded.id, rol: decoded.rol },
              jti: decoded.jti
            };
          }
        } catch (err) {
          console.warn("Token inválido o expirado:", err.message);
        }
      }

      return { currentUser: null, jti: null };
    }
  });

  console.log(`🔐 Subgrafo de Seguridad levantado exitosamente en: ${url}`);
}

main().catch((err) => {
  console.error("❌ Error fatal al iniciar el subgrafo de Seguridad:", err);
  process.exit(1);
});