import 'dotenv/config';
import { ApolloServer } from '@apollo/server';
import { startStandaloneServer } from '@apollo/server/standalone';
import { buildSubgraphSchema } from '@apollo/subgraph';
import { parse } from 'graphql';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import mongoose from 'mongoose';
import amqp from 'amqplib';
import bcrypt from 'bcrypt';
import jwt from 'jsonwebtoken';
import { UsuarioModel } from './infrastructure/mongoose-models.js';
import { runtimeConfig } from './infrastructure/runtime-config.js';
import { Usuario } from './domain/entities.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const typeDefs = parse(fs.readFileSync(path.join(__dirname, 'schema.graphql'), 'utf8'));

async function conectarBaseDatos() {
  try {
    await mongoose.connect(runtimeConfig.mongoUri);
    console.log("🔥 Conexión exitosa a MongoDB (seguridad-service).");
  } catch (error) {
    console.error("❌ Error de conexión a MongoDB:", error.message);
    process.exit(1);
  }
}

// Inicializar conexión con el Broker de Mensajería (RabbitMQ)
let rabbitChannel;
async function initRabbit() {
  try {
    const conn = await amqp.connect(runtimeConfig.rabbitMqUrl);
    rabbitChannel = await conn.createChannel();
    await rabbitChannel.assertQueue('transmisiones-auditoria', { durable: true });
    console.log("RabbitMQ conectado. Canal listo para el dominio de Seguridad.");
  } catch (err) {
    console.error("No se pudo establecer conexión con RabbitMQ:", err.message);
  }
}

function emitirEvento(event, payload) {
  if (!rabbitChannel) return;
  rabbitChannel.sendToQueue(
    'transmisiones-auditoria',
    Buffer.from(JSON.stringify({ event, payload: { ...payload, fecha: new Date() } })),
    { persistent: true }
  );
  console.log(`Evento '${event}' enviado asíncronamente al broker.`);
}

function aDTO(doc) {
  return {
    id: doc._id,
    matricula: doc.matricula,
    nombre: doc.nombre,
    email: doc.email,
    rol: doc.rol,
    activo: doc.activo
  };
}

const resolvers = {
  Query: {
    verUsuario: async (_, { id }) => {
      const doc = await UsuarioModel.findById(id);
      if (!doc) return null;
      return aDTO(doc);
    },

    allUsuarios: async () => {
      const docs = await UsuarioModel.find({});
      return docs.map(aDTO);
    }
  },

  Mutation: {
    registrarUsuario: async (_, { matricula, nombre, email, password, rol }) => {
      // 1. Validar reglas de negocio usando la clase pura del dominio
      const usuarioDominio = new Usuario(null, matricula, nombre, email, rol);
      usuarioDominio.validarMatricula();
      usuarioDominio.validarRol();

      // 2. Verificar que no exista ya un usuario con esa matrícula o email
      const yaExiste = await UsuarioModel.findOne({ $or: [{ matricula }, { email }] });
      if (yaExiste) {
        throw new Error("Ya existe un usuario registrado con esa matrícula o email.");
      }

      // 3. Hashear la contraseña antes de persistir (nunca se guarda en texto plano)
      const passwordHash = await bcrypt.hash(password, 10);

      // 4. Guardar en la persistencia
      const nuevoUsuario = new UsuarioModel({ matricula, nombre, email, passwordHash, rol });
      const doc = await nuevoUsuario.save();

      // 5. Emitir evento de dominio a RabbitMQ para auditoría
      emitirEvento("USUARIO_REGISTRADO", { id: doc._id, matricula: doc.matricula });

      return aDTO(doc);
    },

    login: async (_, { email, password }) => {
      const doc = await UsuarioModel.findOne({ email });
      if (!doc) {
        throw new Error("Credenciales inválidas.");
      }

      const passwordCorrecta = await bcrypt.compare(password, doc.passwordHash);
      if (!passwordCorrecta) {
        throw new Error("Credenciales inválidas.");
      }

      if (!doc.activo) {
        throw new Error("Este usuario está deshabilitado.");
      }

      const token = jwt.sign(
        { id: doc._id.toString(), rol: doc.rol },
        runtimeConfig.jwtSecret,
        { expiresIn: '8h' }
      );

      emitirEvento("USUARIO_LOGIN", { id: doc._id, email: doc.email });

      return { token, usuario: aDTO(doc) };
    }
  },

  Usuario: {
    __resolveReference: async (reference) => {
      const doc = await UsuarioModel.findById(reference.id);
      if (!doc) return null;
      return aDTO(doc);
    }
  }
};

// --- Arranque del servidor ---
async function main() {
  await conectarBaseDatos();
  await initRabbit();

  const server = new ApolloServer({
    schema: buildSubgraphSchema([{ typeDefs, resolvers }])
  });

  const port = runtimeConfig.port;
  const { url } = await startStandaloneServer(server, {
    listen: { port }
  });

  console.log(`🔐 Subgrafo de Seguridad levantado exitosamente en: ${url}`);
}

main().catch((err) => {
  console.error("❌ Error fatal al iniciar el subgrafo de Seguridad:", err);
  process.exit(1);
});
