import neo4j from 'neo4j-driver';
import { getDriver } from '../infrastructure/database.js';

function toNumber(value) {
  return neo4j.isInt(value) ? value.toNumber() : value;
}

function sortTree(nodes) {
  nodes.sort((a, b) => (a.order ?? 0) - (b.order ?? 0));
  for (const node of nodes) {
    sortTree(node.children);
  }
}

export const rbacService = {
  async validarAccesoRuta(userId, path) {
    const session = getDriver().session({ defaultAccessMode: neo4j.session.READ });
    try {
      const cypher = `
        MATCH (u:User {id: $userId})-[:HAS_ROLE]->(r:Role)
        MATCH (r)-[:INHERITS*0..]->(effectiveRole:Role)-[:CAN_ACCESS]->(rt:Route {path: $path})
        RETURN count(rt) > 0 AS autorizado
      `;
      const result = await session.run(cypher, { userId, path });
      return result.records[0]?.get('autorizado') ?? false;
    } finally {
      await session.close();
    }
  },

  async obtenerMenuUsuario(userId) {
    const session = getDriver().session({ defaultAccessMode: neo4j.session.READ });
    try {
      const cypher = `
        MATCH (u:User {id: $userId})-[:HAS_ROLE]->(r:Role)
        MATCH (r)-[:INHERITS*0..]->(effectiveRole:Role)-[:CAN_VIEW_MENU]->(m:MenuNode)
        WITH DISTINCT m
        OPTIONAL MATCH (m)-[:NAVIGATES_TO]->(rt:Route)
        OPTIONAL MATCH (parent:MenuNode)-[:HAS_CHILD]->(m)
        RETURN m.id AS id, m.title AS title, m.order AS order,
               head(collect(DISTINCT rt.path)) AS path,
               collect(DISTINCT parent.id) AS parentIds
      `;
      const result = await session.run(cypher, { userId });

      const nodes = new Map();
      for (const record of result.records) {
        const id = record.get('id');
        nodes.set(id, {
          id,
          title: record.get('title'),
          order: toNumber(record.get('order')),
          path: record.get('path'),
          children: []
        });
      }

      const roots = [];
      for (const record of result.records) {
        const node = nodes.get(record.get('id'));
        const parentIds = record.get('parentIds') ?? [];
        const parentId = parentIds.find((candidate) => nodes.has(candidate));
        if (parentId && parentId !== node.id) {
          nodes.get(parentId).children.push(node);
        } else {
          roots.push(node);
        }
      }

      sortTree(roots);
      return roots;
    } finally {
      await session.close();
    }
  }
};
